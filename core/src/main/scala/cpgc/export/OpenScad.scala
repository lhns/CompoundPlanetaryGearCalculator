package cpgc.`export`

import cpgc.domain.{CompoundDesign, Stage}

/** Emit a parametric OpenSCAD script that describes the geometry of a winning
  * compound design. Uses the popular `gears.scad` API conventions; users supply
  * the library themselves (e.g. `use <gears.scad>` from Chris Wallace / nophead).
  */
object OpenScad:

  def emit(d: CompoundDesign, includePath: String = "gears.scad"): String =
    val sb = StringBuilder()
    sb ++= s"""// Generated by cpgc — Compound Planetary Gear Calculator
               |// Mode: ${d.modeName} Ratio: ${"%.4f".format(d.ratio.value)}:1   Eff: ${"%.3f".format(d.efficiency)}
               |// Layout note: stages are stacked along +Z. For non-PlanetStack
               |// couplings (Ring↔Sun, Ring↔Ring, Sun↔Sun), the welded shaft is
               |// not modelled — adjust translation/orientation manually to
               |// match the physical assembly.
               |use <$includePath>;
               |
               |""".stripMargin
    sb ++= stageBlock("stage1", d.stage1, zOffset = 0.0, d.topology.s1Present)
    d.stage2.foreach { s2 =>
      sb ++= "\n"
      sb ++= stageBlock("stage2", s2, zOffset = stageHeight(d.stage1) + 2.0, d.topology.s2Present)
    }
    sb ++= "\nstage1();\n"
    if d.stage2.isDefined then sb ++= "stage2();\n"
    sb.toString

  private def stageHeight(s: Stage): Double = math.max(6.0, s.module.value * 6.0)

  private def stageBlock(name: String, s: Stage, zOffset: Double, sunPresent: Boolean): String =
    val z = stageHeight(s)
    val module = s.module.value
    val sun    = s.set.sun.toInt
    val planet = s.set.planet.toInt
    val ring   = s.set.ring.toInt
    val n      = s.set.numPlanets
    // A sun-less stage has no sun gear (its tooth count is only a virtual one).
    val sunGear =
      if sunPresent then s"spur_gear(modul=$module, tooth_number=$sun, width=$z, bore=4, pressure_angle=20, helix_angle=0, optimized=false);"
      else "// (no sun gear in this stage)"
    s"""module $name() {
       |  translate([0, 0, $zOffset]) {
       |    // sun
       |    $sunGear
       |    // planets
       |    for (i = [0:${n - 1}]) {
       |      rotate([0, 0, i * 360 / $n])
       |        translate([${"%.4f".format(module * (sun + planet) / 2.0)}, 0, 0])
       |          spur_gear(modul=$module, tooth_number=$planet, width=$z, bore=3, pressure_angle=20, helix_angle=0, optimized=false);
       |    }
       |    // ring
       |    ring_gear(modul=$module, tooth_number=$ring, width=$z, rim_width=$module*2, pressure_angle=20, helix_angle=0);
       |  }
       |}
       |""".stripMargin
